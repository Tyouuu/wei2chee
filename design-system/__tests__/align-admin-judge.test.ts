/* 考后台那把尺的第五根轴 —— 动效。
 *
 * 老板 2026-09-04 挑了 arhamkhnz 当我们系统唯一的样子，然后问了一句
 * `只是你能完全的复刻吗？`。
 *
 * ── 这个档案为什么存在 ────────────────────────────────────────────────────
 * 「完全」照 [重点 7i](../../docs/founder-points.md) 是**五根轴**：
 * 版面 · 字体 · 颜色 · 动效 · 留白，缺一根就是没抄完。
 *
 * 而 `align:admin` 在 2026-09-04 之前**只有四根** —— 它量侧栏宽、字级阶梯、
 * 有颜色的面积、卡片内距，**一个字都没有量动效**。
 * 所以「抄完了」这句话，在那之前是拿一把缺一根轴的尺量出来的。
 *
 * 抄手机那十五套的时候动效永远印「量不到」，那是诚实的 ——
 * 商店页只有静图。**后台这一边参考页是活的，所以量得到，没有借口。**
 *
 * ── 为什么要考「判断」这一层，而不只是跑一次看它印什么 ──────────────────
 * 跑一次只证明它**印得出一个数字**。
 * 这个仓库栽在「印得出数字而数字是错的」上至少四次
 * （见 `probe-image.test.ts` 的档头，一天八次）。
 * 下面每一条都**故意给它一组会红的读数**，看它真的红 ——
 * 没有人看过它红的守卫，等於没有守卫。
 */
import { describe, expect, it } from "vitest";
import { judge } from "@/scripts/align-admin.mjs";

describe("动效那一根轴，判得出对错", () => {
  /* 这一条的门槛是**故意松**的：动效上「有没有」远比「差几毫秒」重要。
     一个完全不动的页面跟一个会动的页面是两种东西；
     而 97 处对 35 处，没有人分得出来 —— 那是内容多寡，不是设计。 */
  it("他们会动而我们完全不动 —— 红", () => {
    expect(judge("动效几处", 97, 0)).toBe("差");
  });

  it("他们会动我们也会动 —— 过，数量差多少不判", () => {
    expect(judge("动效几处", 97, 35)).toBe("ok");
  });

  it("他们不动我们会动 —— 不判它错", () => {
    /* 我们多一点过场，不是没抄到它。这一条留成 ok 是判断不是漏掉：
       参考页里有静态 HTML 的模版（Tabler 的单据页就是），
       拿「他们完全不动」去要求我们也不准动，是把一个技术限制抄成设计。 */
    expect(judge("动效几处", 0, 35)).toBe("ok");
  });

  it("时长差 80ms 以上 —— 红", () => {
    expect(judge("动的时长", 150, 400)).toBe("差");
  });

  it("时长差 80ms 以内 —— 过（官网那把尺的分级里还在同一级）", () => {
    expect(judge("动的时长", 150, 140)).toBe("ok");
    expect(judge("动的时长", 150, 220)).toBe("ok");
  });

  /* ⚠️ 量不到要讲「量不到」，不可以讲「对」也不可以讲「错」。
     跨网域的样式表读 .cssRules 会抛 —— **「看不到」跟「没有」不是同一句话**，
     而这个仓库被「量不到却印一个漂亮数字」的尺骗过至少四次。 */
  it("读不到就回问号，不回过也不回红", () => {
    expect(judge("动效几处", null, 35)).toBe("?");
    expect(judge("动的时长", 150, null)).toBe("?");
  });
});

describe("尺子本来那四根轴还在", () => {
  /* 加第五根轴的时候最容易做的坏事，是顺手把前四根的门槛动一动让数字好看。
     这几条把它们钉住。 */
  it.each([
    ["侧栏宽", 271, 220, "差"],
    ["侧栏宽", 271, 260, "ok"],
    ["字级阶梯", 7, 8, "ok"],
    ["字级阶梯", 7, 3, "差"],
    ["有颜色", 0.3, 1.2, "ok"],
    ["有颜色", 0.3, 19, "差"],
    ["卡片内距", 16, 6, "差"],
    ["卡片内距", 16, 14, "ok"],
  ])("%s %s → %s = %s", (name, ref, ours, want) => {
    expect(judge(name as string, ref as number, ours as number)).toBe(want);
  });
});
