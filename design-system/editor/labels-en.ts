/**
 * The editor, in English.
 *
 * ── WHY THIS FILE EXISTS ──────────────────────────────────────────────────
 *
 * The founder, 2026-08-25, with a screenshot of 「＋ 加一段」 sitting on an
 * otherwise English page: 「明明选择了英文 作为language 为什么还是有那么多华语字
 * 的呢」. He is right, and it is one bug with a wide surface: puck-config.tsx
 * carries 489 unique Chinese strings as `label:` and `title:` literals, and a
 * literal cannot follow a locale. Switching the interface to English changed
 * the top bar (next-intl) and nothing else -- every block name, every category
 * heading, every field label and every 换个款式 option stayed Chinese.
 *
 * ── WHY A MAP RATHER THAN next-intl KEYS ──────────────────────────────────
 *
 * The obvious fix is to replace each literal with `t("blocks.recordTable")`.
 * That is 489 edits across two files that are also imported by SERVER modules
 * (lib/portal/layout-ops.ts, components/auth-shell.tsx), and next-intl's hooks
 * cannot be called from either. It also gives every one of those 489 sites a
 * chance to be missed, which is precisely how this product has already lost
 * 315 register preferences and two whole capability layers.
 *
 * Keying on the Chinese string means the Chinese config stays the single
 * source of truth and English is a projection of it. A missing translation
 * falls through to the Chinese, which is the correct failure: a Chinese word
 * in an English editor is a gap, an empty label is a broken control.
 *
 * ── WHERE IT IS APPLIED ───────────────────────────────────────────────────
 *
 * puck-config-client.tsx, which is already the one place that wraps the whole
 * config for the client and already knows things the server config cannot.
 * Same argument as the register preferences it applies there: a component is
 * translated BY BEING REGISTERED, with no second step to remember.
 *
 * ── WHAT IS DELIBERATELY NOT HERE ─────────────────────────────────────────
 *
 * `defaultProps` -- the sample content a freshly added block arrives with. That
 * is the CUSTOMER'S content, not Formae's chrome, so it follows the system
 * language (projects.system_language), not the owner's interface. Translating
 * it here would put English sample rows into a Chinese system whenever the
 * owner happened to be reading the editor in English. It is a real gap and it
 * is a different one; see docs/founder-tasks.md task 8.
 */

