/**
 * `/portal/<pageKey>` 打开的是哪一边 —— 他的系统，还是编辑器。
 *
 * ── 为什么有这一支 ────────────────────────────────────────────────────────
 *
 * 老板 2026-09-05：`编辑器跟这套 system 都在我的 formae 里面
 * 我好像是做了两套产品 能不能融合呢`。
 *
 * 不是两套产品，是**一个产品把它的施工工具当成了正门**。量出来的：在编辑器里
 * 打开报价单，画布里有 **10 个真的连结**（他自己的侧栏、他的六页、「加一单」），
 * **一个都点不动** —— Puck 把画布上每一次点击都收去当「选中这一块」，
 * 连 Playwright 的 `force` 都走不过去。他每天要做的每一件事，都锁在门后。
 *
 * 所以融合的做法不是把两个画面合成一个，是**把顺序倒过来**：
 * 默认进「用」，「改设计」是一颗按钮。
 *
 * ⚠️ 手机上 2026-09-04 就是这样做的（`mobile-editor.tsx` 那两格，默认停在
 * 「用」）。桌面晚了一天，而这一支把两边收敛成同一个决定。
 *
 * ── 🔴 2026-09-07：分界线拿掉了，老板拍的板 ─────────────
 *
 * 这一支 9-05 写的时候只把门翻了一半：**保存过的**进系统，
 * 而一个从来没保存过的新老板还是落在编辑器上 —— 理由写着
 * 「那是看看你的系统、改改看，也是我们卖的那一屏」。
 *
 * 🔴 **而那一屏里，他自己的按钮一颗都按不动**。浏览器逐字讲的：
 * `<a href="/en/portal/customers/new">New customer</a>` —— 看得见 · 能按 ·
 * 位置稳定，而那一层「可以拖拉」的包装把点击拦下来；
 * **重试 55 次 · 30 秒 · 一次都没穿过去**（装修跟五金两行读数一模一样）。
 *
 * 所以那一屏卖的不是「你的系统」，是「你的系统按不动」。
 * 一个需要气泡教他怎么用的第一屏，本身就是答案：
 * NN/g 实测 70 个人 —— **读过教学的人觉得任务更难**（4.92 对 5.49），
 * 成功率没变好；他们的结论是不要做教学，把介面做得好用。
 *
 * ⚠️ 而它跟重点 11（那一屏就是产品）**不冲突**：
 * 重点 11 讲的是他掏钱之前用眼睛判断的那一次，而一个**按得动**的系统
 * 比一个按不动的工具更像那一屏。「改设计」就在顶上，一下就到。
 *
 * ⚠️ 手机上 9-04 就是这样做的（`mobile-editor.tsx` 默认停在「用」）。
 * 两个屏幕两个正门，正是他讲的「像两个人做的」。
 *
 * ── 为什么是一支函式，不是三个 if ───────────────────────────────────────
 *
 * 这条规矩有三个消费端：进不进编辑器 · 那颗「改设计」画不画 · 编辑器里那条
 * 「← 我的系统」画不画。第一版把第三个写成 `isGeneratedDraft ? null : …`，
 * 而那问的是**这一页**保存过没有 —— 於是在 demo 上返回那一条没有画出来，
 * 而目的地明明在。**同一条规矩写在两个地方，第二份迟早会漂**，
 * 这个仓库栽在这个形状上至少六次。
 */

export type FrontDoor = "system" | "editor";

export function frontDoor({
  isOwner,
  design,
  add,
  tpl,
}: {
  /** 师傅 / 会计不是老板。见 work-view.tsx：把编辑器给他，然后在伺服器上
   *  一个一个拒绝他，是两个答案里比较糟的那一个。 */
  isOwner: boolean;
  /** `?design=1` —— 他自己按了「改设计」。 */
  design?: string;
  /** `?add=` / `?tpl=` —— 这两个参数本身就是「加一块」跟「套一个模版」，
   *  它们的目的地就是设计。 */
  add?: string;
  tpl?: string;
}): FrontDoor {
  /* 🔴 师傅**永远**到不了编辑器，`?design=1` 也不行 —— 一个网址参数不可以
     变成一条绕过角色的路。这里不是执法（`project_pages` 根本没有写入政策），
     但一个把他带到一整屏他按不动的控件前面的产品，是无礼，不是安全。 */
  if (!isOwner) return "system";
  if (design === "1" || Boolean(add) || Boolean(tpl)) return "editor";
  /* 🔴 而其余每一次都是他的系统 —— 保存过没有不再是问题。见档头。 */
  return "system";
}
