import { fontVariables } from "@/app/fonts";
import "../globals.css";

/**
 * 一个经销商自己那一页的根 —— 第三个根 layout。
 *
 * ── 为什么要一个 ──────────────────────────────────────────────────────────
 *
 * 🔴 **看图才看到的。** 第一版没有这个档案，於是 `/p/<号码>` 底下
 * 一行 CSS 都没有载入：整页衬线字、没有边框、没有间距 ——
 * 而每一个 Tailwind class 都还好好写在那里，什么都没报错。
 * 一个经销商在手机上打开它，看到的是一张坏掉的纸。
 *
 * `app/s/layout.tsx` 的档头讲的是同一件事：`app/[locale]/` 底下那一个
 * 是 Formae 在跟老板讲话（网址里有语言 · next-intl · 我们的分享卡 ·
 * 我们的标题）—— 那几样一个都不属於一条发给经销商的连结。
 *
 * ── 故意没有的 ────────────────────────────────────────────────────────────
 *
 * 没有 next-intl：这一页讲的是**那套系统自己的语言**
 * （`party_portal` 回的 `lang`，20260905780000），不是打开它的人
 * 浏览器设定的语言。一个经销商换了手机语言，不该换掉他老板系统的用字。
 *
 * 没有我们的标题跟分享卡：这一页上不该出现 Formae 这个字 ——
 * 那是那门生意在跟它的下游讲话。
 *
 * ── lang="en" ─────────────────────────────────────────────────────────────
 *
 * 跟 `/s/` 同一个理由跟同一个限制：那是预设值，而真正的语言要那个号码
 * 才查得到，layout 拿不到。页面自己的 `<main lang=...>` 会讲对，
 * 而 `<html lang>` 由子层设不了。
 */
export default function PartyPortalLayout({ children }: { children: React.ReactNode }) {
  return (
    /* 🔴 **自己铺白底，不要靠 globals.css 那块地。**
       那一块是 Formae 的壳，而它是**深色的** —— 第一版没有铺，
       於是这一页是近黑底配近黑字，读不出来，而每一条断言都是绿的
       （版心有宽、按钮有底色，两个都对，而画面是坏的）。
       重点 7l：数字过关不等於眼睛过关。 */
    <html lang="en" className={fontVariables}>
      <body className="bg-white text-neutral-900">{children}</body>
    </html>
  );
}
